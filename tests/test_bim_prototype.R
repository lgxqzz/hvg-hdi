test_that("prototype returns the objective at exactly the counted M steps", {
  x <- c(-5,-3,-2,0,1,3,5,10)
  means <- as.numeric(quantile(x,c(.15,.85))); sig <- sd(x)
  joint <- cbind(.5*dnorm(x,means[1],sig),.5*dnorm(x,means[2],sig))
  r <- joint/rowSums(joint); w <- colMeans(r)
  mu <- colSums(r*x)/colSums(r)
  s <- sqrt(colSums(r*outer(x,mu,"-")^2)/colSums(r))
  ll <- sum(log(w[1]*dnorm(x,mu[1],s[1])+w[2]*dnorm(x,mu[2],s[2])))
  f <- fit_bim_prototype(x,2,max_steps=1,tolerance=1e-15)
  expect_equal(f$weights,w); expect_equal(f$means,mu); expect_equal(f$sds,s)
  expect_equal(f$loglik,ll,tolerance=1e-12)
  expect_equal(f$criterion,5*log(length(x))-2*ll,tolerance=1e-12)
  expect_equal(f$objective_change,ll-sum(log(rowSums(joint))),tolerance=1e-12)
  expect_identical(f$steps,1L); expect_false(f$converged)
  expect_identical(f$reason,"nonconverged")
  expect_equal(fit_bim_prototype(x,2,max_steps=2,tolerance=1e-15)$steps,2L)
  early <- fit_bim_prototype(x,2,max_steps=2,tolerance=1e9)
  expect_identical(early$steps,1L); expect_true(early$converged)
})
test_that("prototype diagnostics distinguish invalid, boundary and nonconverged fits", {
  expect_identical(fit_bim_prototype(rep(1,8),2)$reason,"degenerate_input")
  expect_identical(fit_bim_prototype(c(1,NA,2),2)$reason,"invalid_input")
  z <- c(rep(-5,70),rep(5,30))
  f <- fit_bim_prototype(z,2,max_steps=200)
  expect_true(f$converged); expect_true(f$boundary)
  expect_identical(f$reason,"boundary"); expect_equal(1-max(f$weights),.3)
  expect_equal(min(f$sds),1e-6)
  expect_error(fit_bim_prototype(z,2,max_steps=5001),"max_steps")
  expect_error(fit_bim_prototype(z,2,tolerance=0),"tolerance")
  expect_error(fit_bim_prototype(z,2,span=c(.9,.1)),"span")
})
test_that("selection rejects its winner without candidate rescue", {
  bad <- list(k=2L,finite=TRUE,criterion=0,weights=c(.8,.2),converged=FALSE,boundary=FALSE,reason="nonconverged")
  good <- list(k=3L,finite=TRUE,criterion=10,weights=c(.5,.3,.2),converged=TRUE,boundary=FALSE,reason="ok")
  s <- select_bim_prototype(list(bad,good))
  expect_false(s$accepted); expect_identical(s$fit$k,2L); expect_identical(s$reason,"nonconverged")
  bad$converged <- TRUE; bad$boundary <- TRUE; bad$reason <- "boundary"
  expect_identical(select_bim_prototype(list(bad,good))$reason,"boundary")
  bad$finite <- FALSE
  expect_identical(select_bim_prototype(list(bad,good))$fit$k,3L)
  good$finite <- FALSE
  expect_identical(select_bim_prototype(list(bad,good))$reason,"all_invalid")
})
