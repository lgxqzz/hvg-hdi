testthat::test_that("separate definitions preserve complete references and exact formulas",{
  x <- cbind(IQR=1:6,MAD=c(1,2,4,5,8,9),ENT=c(2,4,3,7,6,8),Gini=c(7,3,1,6,5,2),BIM=c(.1,.2,.4,.3,.5,.6))
  ids <- paste0("s",1:6); rownames(x)<-ids
  r4 <- freeze_dispersion_reference(x[,1:4],ids); r5 <- freeze_dispersion_reference(x,ids)
  a <- setNames(rep(TRUE,6),ids)
  s4 <- score_experimental_dispersion(x[,1:4],ids,r4,"HDI_4")
  s5 <- score_experimental_dispersion(x,ids,r5,"HDI_5",a)
  testthat::expect_equal(s4$score,unname(rowMeans(scale(x[,1:4]))))
  testthat::expect_equal(s5$score,unname(rowMeans(scale(x))))
  testthat::expect_identical(r4$sample_sd,r5$sample_sd[1:4])
  testthat::expect_equal(unname(r4$sample_sd[1]),sqrt(sum((1:6-3.5)^2)/5))
  testthat::expect_identical(s4[,2:5],s5[,2:5])
  testthat::expect_error(score_experimental_dispersion(x[1:2,],ids[1:2],r5,"HDI_5",a),"entire frozen scoring cohort")
  testthat::expect_error(score_experimental_dispersion(x,ids,r5,c("HDI_4","HDI_5"),a),"Choose")
  testthat::expect_error(score_experimental_dispersion(x,ids,r5,NA_character_,a),"Choose")
  a[2]<-FALSE
  testthat::expect_error(score_experimental_dispersion(x,ids,r5,"HDI_5",a),"entire frozen")
  testthat::expect_error(score_experimental_dispersion(x,ids,r5,"HDI_5"),"entire frozen")
  testthat::expect_error(score_experimental_dispersion(x,rev(ids),r5,"HDI_5",a),"alignment")
  testthat::expect_error(freeze_dispersion_reference(x,rev(ids)),"alignment")
  testthat::expect_error(score_experimental_dispersion(x[,1:4],ids,r5,"HDI_4"),"mismatch")
  a[]<-TRUE; names(a)<-rev(ids)
  testthat::expect_error(score_experimental_dispersion(x,ids,r5,"HDI_5",a),"entire frozen")
  x[,5]<-0; r0<-freeze_dispersion_reference(x,ids)
  testthat::expect_error(score_experimental_dispersion(x,ids,r0,"HDI_5",setNames(rep(TRUE,6),ids)),"constant")
  testthat::expect_equal(score_experimental_dispersion(x[1:2,1:4],ids[1:2],r4,"HDI_4")$score,s4$score[1:2])
})
testthat::test_that("count scenarios retain longitudinal dimensions and latent membership",{
  for(regime in c("unimodal","balanced2","separated3","unbalanced")) {
    d <- generate_mixture_scenario(regime,92301)
    testthat::expect_identical(d,generate_mixture_scenario(regime,92301))
    testthat::expect_identical(dim(d$counts),c(1200L,48L))
    testthat::expect_true(all(d$counts>=0 & d$counts==round(d$counts)))
    testthat::expect_identical(dimnames(d$counts),dimnames(d$latent))
    testthat::expect_true(all(table(d$metadata$participant_id)==3))
    testthat::expect_equal(length(unique(d$genes$group)),length(d$parameters$probabilities))
    testthat::expect_equal(d$parameters$NB_size,12)
  }
  testthat::expect_error(generate_mixture_scenario("unknown",1),"Unknown")
})
